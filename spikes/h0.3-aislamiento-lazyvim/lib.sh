# shellcheck shell=sh
# shellcheck disable=SC2016,SC2028,SC1003 # this file writes shell code: literal $, \n and quotes are intended
# Spike H0.3 — reusable library: installs the tools with the isolated mise of
# H0.1, and generates the per-tool wrappers, .host-sh, the session launcher
# (spike stand-in for `ditto up`) and the bash/zsh session rc files.
#
#   H03_DIR=spikes/h0.3-aislamiento-lazyvim
#   . "$H03_DIR/lib.sh"
#   h03_paths "$PWD/.ditto"           # DITTO_ROOT + H0.1 paths (exports no MISE_*)
#   h03_install_tools                 # mise bootstrap + install --locked (sha256)
#   h03_write_wrappers                # .ditto/bin/{nvim,lazygit,rg,fd,fzf,tree-sitter,.host-sh}
#   h03_write_session                 # .ditto/shell/{session,bashrc,zsh/.zshenv,zsh/.zshrc}
#   h03_install_starter               # LazyVim starter -> .ditto/config/nvim
#
# Every generated file is POSIX sh (zsh files excepted) with absolute paths
# baked in, as ditto (Go) would generate them. Throwaway spike code.

# H03_DIR must point at this directory; H0.1 lives next to it.
: "${H03_DIR:?set H03_DIR to the spike directory before sourcing lib.sh}"
H01_DIR=${H01_DIR:-$H03_DIR/../h0.1-mise-aislado}
# shellcheck source=../h0.1-mise-aislado/env.sh
. "$H01_DIR/env.sh"

# Variables the nvim wrapper changes and every other wrapper restores.
H03_SAVED_VARS="XDG_CONFIG_HOME XDG_DATA_HOME XDG_STATE_HOME XDG_CACHE_HOME PATH GIT_CONFIG_GLOBAL TMPDIR"

# Mechanism for git launched by nvim *directly* (argument list: gitsigns,
# lazy.nvim, vim.system): those processes keep nvim's XDG_CONFIG_HOME.
#   none     nothing (git misses $XDG_CONFIG_HOME/git/*)
#   global   arch.md §8 as written: GIT_CONFIG_GLOBAL=~/.config/git/config if it exists
#   include  .ditto/config/git/config = [include] path = <user XDG git dir>/config (#4)
#   symlink  .ditto/config/git -> <original XDG_CONFIG_HOME or ~/.config>/git
H03_GIT_MODE=${H03_GIT_MODE:-symlink}

# h03_paths <ditto_root> — H0.1 paths plus DITTO_ROOT (exported, not MISE_*).
h03_paths() {
	ditto_mise_paths "$1" || return 1
	DITTO_ROOT=$DITTO_DIR
	export DITTO_ROOT
}

# h03_write_mise_config <file> — the subset of the H0.1 catalogue this spike
# needs (no OpenCode). Versions and backends come from env.sh.
h03_write_mise_config() {
	{
		echo '# Generated by spikes/h0.3-aislamiento-lazyvim (subset of H0.1).'
		echo '[tools]'
		case "$(ditto_nvim_tool)" in
		aqua:*) echo "\"aqua:neovim/neovim\" = \"$DITTO_V_NVIM\"" ;;
		github:*) echo "\"github:neovim/neovim-releases\" = \"$DITTO_V_NVIM_LEGACY\"" ;;
		*) echo "no Neovim build for this libc" >&2; return 1 ;;
		esac
		echo "\"github:BurntSushi/ripgrep\" = \"$DITTO_V_RG\""
		echo "\"aqua:sharkdp/fd\" = \"$DITTO_V_FD\""
		echo "\"aqua:junegunn/fzf\" = \"$DITTO_V_FZF\""
		echo "\"aqua:jesseduffield/lazygit\" = \"$DITTO_V_LAZYGIT\""
		[ -n "$(ditto_treesitter_tool)" ] && echo "\"conda:tree-sitter-cli\" = \"$DITTO_V_TREESITTER\""
	} >"$1"
}

# h03_install_tools — bootstraps mise (sha256 embedded in env.sh) and installs
# the tools from the shared H0.1 lock (sha256 per asset). Requires h03_paths.
h03_install_tools() {
	ditto_mise_bootstrap || return 1
	h03_write_mise_config "$DITTO_MISE_CONFIG" || return 1
	cp "$H01_DIR/mise.lock" "$DITTO_MISE_LOCK"
	ditto_mise install --locked >&2
}

# h03_tool <bin> — absolute path of a mise-installed binary.
h03_tool() {
	ditto_mise which "$1"
}

# _h03_q <string> — single-quotes a string for a generated sh script.
_h03_q() {
	printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
}

# _h03_restore_block — sh snippet that undoes the nvim wrapper (only if we run
# under it: DITTO_NVIM=1). An unset variable is restored as unset.
_h03_restore_block() {
	echo '# Undo the nvim wrapper (no-op outside nvim): unset vars stay unset.'
	echo 'if [ "${DITTO_NVIM-}" = 1 ]; then'
	for _v in $H03_SAVED_VARS; do
		printf '\tif [ -n "${DITTO_ORIG_%s+x}" ]; then export %s="$DITTO_ORIG_%s"; else unset %s; fi\n' \
			"$_v" "$_v" "$_v" "$_v"
	done
	printf '\tunset DITTO_NVIM'
	for _v in $H03_SAVED_VARS; do printf ' DITTO_ORIG_%s' "$_v"; done
	echo
	echo 'fi'
}

# _h03_header <description> — shebang, generated-file comment and `set -eu`
# (docs/code_standards.md §5) for every generated sh script. The bash/zsh rc
# files do not use it: they are sourced into the user's interactive shell,
# where -e/-u would close the session on the first failing command.
_h03_header() {
	printf '#!/bin/sh\n# %s\n# Generated by spikes/h0.3-aislamiento-lazyvim/lib.sh (ditto would generate it).\nset -eu\n' "$1"
}

# h03_runtime_path — extra PATH entries for nvim only (mise runtimes for
# Mason; arch.md §8). The spike simulates one with a marker binary.
h03_runtime_path() {
	echo "${H03_RUNTIME_PATH:-$DITTO_ROOT/spike/runtime/bin}"
}

# h03_write_nvim_wrapper <abs-nvim> — .ditto/bin/nvim.
h03_write_nvim_wrapper() {
	_w="$DITTO_ROOT/bin/nvim"
	_r=$(_h03_q "$DITTO_ROOT")
	{
		_h03_header 'nvim wrapper: XDG_* only for Neovim, originals saved in DITTO_ORIG_* (arch.md §8).'
		echo "DITTO_ROOT=$_r"
		echo 'export DITTO_ROOT'
		echo '# Save the originals once: a nested nvim started as a direct child'
		echo '# (DITTO_NVIM=1 still set) must not overwrite them with ours.'
		echo 'if [ "${DITTO_NVIM-}" != 1 ]; then'
		for _v in $H03_SAVED_VARS; do
			printf '\tif [ -n "${%s+x}" ]; then export DITTO_ORIG_%s="$%s"; fi\n' "$_v" "$_v" "$_v"
		done
		printf '\texport DITTO_NVIM=1\n'
		printf '\texport PATH=%s:"$PATH"\n' "$(_h03_q "$(h03_runtime_path)")"
		case "$H03_GIT_MODE" in
		global)
			echo '	# arch.md §8 (draft): git launched directly by nvim reads ~/.config/git/config.'
			echo '	if [ -z "${GIT_CONFIG_GLOBAL+x}" ] && [ -f "$HOME/.config/git/config" ]; then'
			echo '		export GIT_CONFIG_GLOBAL="$HOME/.config/git/config"'
			echo '	fi'
			;;
		esac
		echo 'fi'
		echo 'export XDG_CONFIG_HOME="$DITTO_ROOT/config" XDG_DATA_HOME="$DITTO_ROOT/data" \'
		echo '	XDG_STATE_HOME="$DITTO_ROOT/state" XDG_CACHE_HOME="$DITTO_ROOT/cache"'
		case "$H03_GIT_MODE" in
		symlink)
			echo '# git launched directly by nvim sees XDG_CONFIG_HOME=.ditto/config: point'
			echo '# .ditto/config/git at the user'"'"'s git dir (config, ignore, attributes,'
			echo '# credentials) so it behaves as on the host.'
			echo '# Writes of those git processes (git config --global, credential store)'
			echo '# land in the user'"'"'s files, exactly as with git outside ditto.'
			echo '_g="${DITTO_ORIG_XDG_CONFIG_HOME:-$HOME/.config}/git"'
			echo '_l="$XDG_CONFIG_HOME/git"'
			echo 'if [ -e "$_l" ] && [ ! -L "$_l" ]; then'
			echo '	# A real file/dir is not ours: never touch it.'
			echo '	echo "ditto: $_l is not a symlink; left untouched (git started by nvim may miss your git config)" >&2'
			echo 'elif [ -d "$_g" ]; then'
			echo '	# ln -sfn replaces the link itself (no descent into a linked dir) on'
			echo '	# GNU and BSD ln; skipped when the link is already right.'
			echo '	[ "$(readlink "$_l" 2>/dev/null || true)" = "$_g" ] || ln -sfn "$_g" "$_l"'
			echo 'elif [ -L "$_l" ]; then'
			echo '	# No user git dir: drop our stale/dangling link (only ever a symlink).'
			echo '	rm -f "$_l"'
			echo 'fi'
			echo 'unset _g _l'
			;;
		include)
			echo '# Alternative proposed by #4: .ditto/config/git/config includes the user'"'"'s'
			echo '# XDG git config (~/.gitconfig is read anyway: it does not depend on XDG).'
			echo '_g="${DITTO_ORIG_XDG_CONFIG_HOME:-$HOME/.config}/git"'
			echo '[ -L "$XDG_CONFIG_HOME/git" ] && rm -f "$XDG_CONFIG_HOME/git"'
			echo 'mkdir -p "$XDG_CONFIG_HOME/git"'
			echo 'if [ -f "$_g/config" ]; then'
			echo '	printf "[include]\\n\\tpath = %s\\n" "$_g/config" >"$XDG_CONFIG_HOME/git/config"'
			echo 'else'
			echo '	rm -f "$XDG_CONFIG_HOME/git/config"'
			echo 'fi'
			echo 'unset _g'
			;;
		esac
		echo '# Temporary files (RPC socket, swap of :terminal jobs...) inside .ditto;'
		echo '# restored for children by .host-sh and the other wrappers.'
		echo 'export TMPDIR="$DITTO_ROOT/tmp"'
		echo 'mkdir -p "$TMPDIR"'
		echo "exec $(_h03_q "$1") \"\$@\""
	} >"$_w"
	chmod 0755 "$_w"
}

# h03_write_tool_wrapper <name> <abs-bin> [VAR=value...] — restore the
# DITTO_ORIG_* (so a tool started from nvim sees the user's environment),
# export the tool's own variables, exec. Values may reference $DITTO_ROOT.
h03_write_tool_wrapper() {
	_n=$1 _b=$2
	shift 2
	_w="$DITTO_ROOT/bin/$_n"
	{
		_h03_header "$_n wrapper: restore DITTO_ORIG_*, tool-specific variables only (arch.md §8)."
		echo "DITTO_ROOT=$(_h03_q "$DITTO_ROOT")"
		echo 'export DITTO_ROOT'
		_h03_restore_block
		for _kv in "$@"; do
			echo "export ${_kv%%=*}=\"${_kv#*=}\""
		done
		echo "exec $(_h03_q "$_b") \"\$@\""
	} >"$_w"
	chmod 0755 "$_w"
}

# h03_write_host_sh — .ditto/bin/.host-sh, Neovim's 'shell'. Restores the
# DITTO_ORIG_* and then:
#   .host-sh -c <cmd> [args]  -> exec "$SHELL" -c <cmd> [args]  (:!, system(), OpenCode)
#   .host-sh                  -> exec the session shell (:terminal, Snacks): same
#                                rc as the subshell (user rc, then .ditto/bin first, HISTFILE)
#   anything else             -> exec "$SHELL" "$@"
h03_write_host_sh() {
	_w="$DITTO_ROOT/bin/.host-sh"
	{
		_h03_header ".host-sh: Neovim's 'shell'; runs the user's \$SHELL with the host environment (arch.md §8)."
		echo "DITTO_ROOT=$(_h03_q "$DITTO_ROOT")"
		echo 'export DITTO_ROOT'
		_h03_restore_block
		echo 'if [ "$#" -eq 0 ]; then'
		echo '	exec "$DITTO_ROOT/shell/session"'
		echo 'fi'
		echo 'exec "${SHELL:-/bin/sh}" "$@"'
	} >"$_w"
	chmod 0755 "$_w"
}

# h03_write_wrappers — all wrappers in .ditto/bin plus the lazygit config dir.
# Requires h03_paths and installed tools.
h03_write_wrappers() {
	mkdir -p "$DITTO_ROOT/bin" "$DITTO_ROOT/config/lazygit" "$DITTO_ROOT/config/ripgrep" \
		"$DITTO_ROOT/config/fzf" "$DITTO_ROOT/data" "$DITTO_ROOT/state" "$DITTO_ROOT/cache" || return 1
	h03_write_nvim_wrapper "$(h03_tool nvim)" || return 1
	# lazygit: CONFIG_DIR keeps state.yml (and the default config) in .ditto;
	# LG_CONFIG_FILE is respected if already set (Snacks.lazygit sets it to
	# "<config>,<theme>").
	h03_write_tool_wrapper lazygit "$(h03_tool lazygit)" \
		'CONFIG_DIR=$DITTO_ROOT/config/lazygit' \
		'LG_CONFIG_FILE=${LG_CONFIG_FILE:-$DITTO_ROOT/config/lazygit/config.yml}' || return 1
	: >>"$DITTO_ROOT/config/ripgrep/config"
	h03_write_tool_wrapper rg "$(h03_tool rg)" 'RIPGREP_CONFIG_PATH=$DITTO_ROOT/config/ripgrep/config' || return 1
	: >>"$DITTO_ROOT/config/fzf/opts"
	h03_write_tool_wrapper fzf "$(h03_tool fzf)" 'FZF_DEFAULT_OPTS_FILE=$DITTO_ROOT/config/fzf/opts' || return 1
	h03_write_tool_wrapper fd "$(h03_tool fd)" || return 1
	if _ts=$(h03_tool tree-sitter 2>/dev/null) && [ -n "$_ts" ]; then
		h03_write_tool_wrapper tree-sitter "$_ts" || return 1
	fi
	h03_write_host_sh
}

# _h03_rc_tail — shared end of the bash/zsh session rc: .ditto/bin first
# (once), history files inside .ditto.
_h03_rc_tail() {
	cat <<'EOF'
# ditto: after the user rc, so conda/pyenv/rc cannot push .ditto/bin back.
case ":$PATH:" in
*":$DITTO_ROOT/bin:"*) PATH=$(printf '%s\n' ":$PATH:" | sed "s|:$DITTO_ROOT/bin:|:|g; s|^:||; s|:\$||") ;;
esac
export PATH="$DITTO_ROOT/bin:$PATH"
# History and similar files go to .ditto/state, never $HOME.
export LESSHISTFILE="$DITTO_ROOT/state/less/history"
export NODE_REPL_HISTORY="$DITTO_ROOT/state/shell/node_repl_history"
export PYTHON_HISTORY="$DITTO_ROOT/state/shell/python_history"
EOF
}

# h03_write_session — .ditto/shell/: the session launcher (what `ditto up`
# would exec) and the rc files. No XDG_* or MISE_* is exported.
h03_write_session() {
	_s="$DITTO_ROOT/shell"
	mkdir -p "$_s/zsh" "$DITTO_ROOT/state/shell" "$DITTO_ROOT/state/less" || return 1
	_r=$(_h03_q "$DITTO_ROOT")
	{
		_h03_header 'session launcher: spike stand-in for `ditto up` (arch.md §12).'
		echo "DITTO_ROOT=$_r"
		echo 'export DITTO_ROOT DITTO_ACTIVE=1'
		echo 'SHELL=${SHELL:-/bin/sh}'
		echo 'case "${SHELL##*/}" in'
		echo 'bash) exec "$SHELL" --rcfile "$DITTO_ROOT/shell/bashrc" -i ;;'
		echo 'zsh)'
		echo '	# Remember the user ZDOTDIR (or that it was unset); our .zshenv/.zshrc'
		echo '	# load the user files from there and restore it for nested shells.'
		echo '	if [ -n "${ZDOTDIR+x}" ]; then export DITTO_ORIG_ZDOTDIR="$ZDOTDIR"; else unset DITTO_ORIG_ZDOTDIR; fi'
		echo '	export ZDOTDIR="$DITTO_ROOT/shell/zsh"'
		echo '	exec "$SHELL" -i ;;'
		echo '*)'
		echo '	export PATH="$DITTO_ROOT/bin:$PATH"'
		echo '	exec "${SHELL:-/bin/sh}" -i ;;'
		echo 'esac'
	} >"$_s/session"
	chmod 0755 "$_s/session"

	{
		echo '# ditto session rc (bash). Generated by spikes/h0.3-aislamiento-lazyvim/lib.sh.'
		echo '# shellcheck shell=bash'
		echo '[ -f "$HOME/.bashrc" ] && . "$HOME/.bashrc"'
		_h03_rc_tail
		echo 'export HISTFILE="$DITTO_ROOT/state/shell/bash_history"'
	} >"$_s/bashrc"
	{
		echo '# ditto session .zshenv. Generated by spikes/h0.3-aislamiento-lazyvim/lib.sh.'
		echo '# Run the user .zshenv with the user ZDOTDIR, then point ZDOTDIR back here'
		echo '# so zsh reads our .zshrc next.'
		echo 'if [[ -n ${DITTO_ORIG_ZDOTDIR+x} ]]; then export ZDOTDIR=$DITTO_ORIG_ZDOTDIR; else unset ZDOTDIR; fi'
		echo '[[ -f ${ZDOTDIR:-$HOME}/.zshenv ]] && source "${ZDOTDIR:-$HOME}/.zshenv"'
		echo '# The user .zshenv may itself set ZDOTDIR (e.g. ~/.config/zsh).'
		echo 'if [[ -n ${ZDOTDIR+x} ]]; then typeset -g _ditto_user_zdotdir=$ZDOTDIR; else unset _ditto_user_zdotdir; fi'
		echo 'export ZDOTDIR="$DITTO_ROOT/shell/zsh"'
	} >"$_s/zsh/.zshenv"
	{
		echo '# ditto session .zshrc. Generated by spikes/h0.3-aislamiento-lazyvim/lib.sh.'
		echo '# Restore the user ZDOTDIR (unset if it was), so nested shells and the'
		echo '# user .zshrc see the original value, then load the user .zshrc.'
		echo 'if [[ -n ${_ditto_user_zdotdir+x} ]]; then export ZDOTDIR=$_ditto_user_zdotdir; else unset ZDOTDIR; fi'
		echo 'unset _ditto_user_zdotdir DITTO_ORIG_ZDOTDIR'
		echo '[[ -f ${ZDOTDIR:-$HOME}/.zshrc ]] && source "${ZDOTDIR:-$HOME}/.zshrc"'
		_h03_rc_tail
		echo 'export HISTFILE="$DITTO_ROOT/state/shell/zsh_history"'
	} >"$_s/zsh/.zshrc"
}

# h03_install_starter [starter-dir] — copies the LazyVim starter to
# .ditto/config/nvim and bootstraps lazy.nvim at the commit pinned in
# lazy-lock.json (git commit = integrity; no unpinned clone).
h03_install_starter() {
	_src=${1:-$H03_DIR/starter}
	_dst="$DITTO_ROOT/config/nvim"
	mkdir -p "$_dst"
	cp -R "$_src/." "$_dst/"
	_lazy="$DITTO_ROOT/data/nvim/lazy/lazy.nvim"
	_commit=""
	[ -f "$_dst/lazy-lock.json" ] &&
		_commit=$(sed -n 's/.*"lazy.nvim": *{ *"branch": *"[^"]*", *"commit": *"\([0-9a-f]*\)".*/\1/p' "$_dst/lazy-lock.json")
	if [ -z "$_commit" ] && [ "${H03_ALLOW_UNPINNED_LAZY:-0}" != 1 ]; then
		echo "h03_install_starter: no lazy.nvim commit in $_dst/lazy-lock.json; refusing an unpinned clone (H03_ALLOW_UNPINNED_LAZY=1 only to generate the lock)" >&2
		return 1
	fi
	if [ ! -d "$_lazy/.git" ]; then
		git clone -q --filter=blob:none --branch=stable https://github.com/folke/lazy.nvim.git "$_lazy" || return 1
	fi
	if [ -n "$_commit" ]; then
		git -C "$_lazy" -c advice.detachedHead=false checkout -q "$_commit" || return 1
	fi
}
