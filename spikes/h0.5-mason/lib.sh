# Spike H0.5 — reusable library on top of H0.3 (which loads H0.1): adds the
# runtimes Mason needs (node, go, python) installed by the isolated mise, puts
# them only in the PATH of the nvim wrapper, and keeps the package-manager
# caches of Mason's children (npm, pip, go) inside .ditto.
#
#   H05_DIR=spikes/h0.5-mason
#   . "$H05_DIR/lib.sh"
#   h05_paths "$PWD/.ditto"         # DITTO_ROOT + H0.1 paths (exports no MISE_*)
#   h05_install_tools               # H0.3 tools + runtimes, mise install --locked
#   h05_write_wrappers              # H0.3 wrappers; nvim gets runtimes + caches
#   h03_write_session               # unchanged from H0.3
#   h03_install_starter "$H05_DIR/starter"
#
# Neither H0.1 nor H0.3 is modified: their functions are reused and only
# H03_SAVED_VARS / H03_RUNTIME_PATH are set before generating the wrappers.
# Throwaway spike code.

: "${H05_DIR:?set H05_DIR to the spike directory before sourcing lib.sh}"
H03_DIR=${H03_DIR:-$H05_DIR/../h0.3-aislamiento-lazyvim}
# shellcheck source=../h0.3-aislamiento-lazyvim/lib.sh
. "$H03_DIR/lib.sh"

# Runtimes for Mason (arch.md §6/§8). Pinned; sha256 per platform in
# $H05_DIR/mise.lock (generated by `run.sh <dest> mise-lock`).
H05_V_NODE="24.22.1"   # LTS "Krypton"
H05_V_GO="1.27.3"
H05_V_PYTHON="3.13.16" # python-build-standalone (core:python precompiled)

# Variables the nvim wrapper sets for Mason's children and every other
# wrapper / .host-sh restores (H0.3 mechanism, extended list).
H05_H03_SAVED_VARS=$H03_SAVED_VARS
H05_CACHE_VARS="npm_config_cache npm_config_devdir PIP_CACHE_DIR GOPATH GOMODCACHE GOCACHE GOTOOLCHAIN GOENV GOPLSCACHE GOLANGCI_LINT_CACHE"

# H05_WRAPPER: "isolated" (default) sets H05_CACHE_VARS inside the nvim
# wrapper; "bare" is the control: H0.3 wrapper + runtimes only.
H05_WRAPPER=${H05_WRAPPER:-isolated}

# h05_paths <ditto_root>
h05_paths() {
	h03_paths "$1"
}

# h05_node_flavor — "" (official build) or "glibc-217" (unofficial build for
# x86_64 hosts with glibc < 2.28; official Node >= 18 needs 2.28). Prints
# "none" when no prebuilt Node exists for this host (arm64 with glibc < 2.28).
# H05_NODE_FLAVOR overrides the detection (e.g. to reproduce the failure).
h05_node_flavor() {
	if [ -n "${H05_NODE_FLAVOR+x}" ]; then
		echo "$H05_NODE_FLAVOR"
		return 0
	fi
	case "$(ditto_libc)" in
	glibc\ *)
		ditto_glibc_at_least 2.28 && { echo ""; return 0; }
		if [ "$(ditto_arch)" = x64 ]; then echo glibc-217; else echo none; fi
		;;
	*) echo "" ;;
	esac
}

# h05_write_mise_config <file> — H0.3 subset + runtimes (and the unofficial
# Node mirror when the host needs the glibc-217 flavour).
h05_write_mise_config() {
	h03_write_mise_config "$1" || return 1
	_fl=$(h05_node_flavor)
	{
		[ "$_fl" = none ] || echo "\"core:node\" = \"$H05_V_NODE\""
		echo "\"core:go\" = \"$H05_V_GO\""
		echo "\"core:python\" = \"$H05_V_PYTHON\""
		if [ "$_fl" = glibc-217 ]; then
			echo
			echo '[settings.node]'
			echo 'flavor = "glibc-217"'
			echo 'mirror_url = "https://unofficial-builds.nodejs.org/download/release/"'
		fi
		echo
		echo '[settings.python]'
		echo 'compile = false' # precompiled only: never build CPython from source
	} >>"$1"
}

# h05_write_lock <out> — H0.1 lock + the runtimes lock of this spike, as one
# file (TOML tables do not collide; the header is kept once).
h05_write_lock() {
	{
		cat "$H01_DIR/mise.lock"
		echo
		sed -e '/^# @generated/d' -e '/^lockfile_version/d' "$H05_DIR/mise.lock"
	} >"$1"
}

# h05_install_tools — mise (sha256) + install --locked of the H0.3 tools and
# the runtimes. Requires h05_paths.
h05_install_tools() {
	ditto_mise_bootstrap || return 1
	h05_write_mise_config "$DITTO_MISE_CONFIG" || return 1
	h05_write_lock "$DITTO_MISE_LOCK"
	ditto_mise install --locked >&2
}

# h05_runtime_path — PATH entries of the mise runtimes (nvim wrapper only).
# `mise which` gives the real binary path (layout differs per backend).
h05_runtime_path() {
	_p=""
	for _b in node go python3; do
		_x=$(h03_tool "$_b" 2>/dev/null) || continue
		[ -n "$_x" ] || continue
		_p="$_p${_p:+:}$(dirname "$_x")"
	done
	echo "$_p"
}

# _h05_cache_exports — sh lines inserted before `exec` in the nvim wrapper.
# Values are saved in DITTO_ORIG_* by the wrapper and restored by .host-sh
# (H03_SAVED_VARS is extended below), so shells and lazygit see the host's.
_h05_cache_exports() {
	cat <<'EOF'
# Mason children (npm/pip/go) and the tools it installs: caches and Go state
# inside .ditto (arch.md §8). On Linux most of them would already follow
# XDG_CACHE_HOME; on macOS Go's os.UserCacheDir and node-gyp use
# ~/Library/Caches, so each one is named.
export npm_config_cache="$DITTO_ROOT/cache/npm"
export npm_config_devdir="$DITTO_ROOT/cache/node-gyp"
export PIP_CACHE_DIR="$DITTO_ROOT/cache/pip"
export GOPATH="$DITTO_ROOT/data/go"
export GOMODCACHE="$DITTO_ROOT/cache/go/mod"
export GOCACHE="$DITTO_ROOT/cache/go/build"
export GOPLSCACHE="$DITTO_ROOT/cache/gopls"
export GOLANGCI_LINT_CACHE="$DITTO_ROOT/cache/golangci-lint"
# The go of mise builds Mason's Go packages: never fetch another toolchain.
export GOTOOLCHAIN=local
# `go env -w` file of the user (GOPROXY, GOPRIVATE...). Linux puts it under
# XDG_CONFIG_HOME, which nvim changes; macOS uses ~/Library/Application Support.
if [ -z "${DITTO_ORIG_GOENV+x}" ] && [ "$(uname -s)" = Linux ]; then
	export GOENV="${DITTO_ORIG_XDG_CONFIG_HOME:-$HOME/.config}/go/env"
fi
# pip under XDG_CONFIG_HOME=.ditto/config would miss the user's pip.conf
# (index-url, proxy, trusted-host): link it like .ditto/config/git.
_p="${DITTO_ORIG_XDG_CONFIG_HOME:-$HOME/.config}/pip"
_l="$XDG_CONFIG_HOME/pip"
if [ -e "$_l" ] && [ ! -L "$_l" ]; then
	echo "ditto: $_l is not a symlink; left untouched" >&2
elif [ -d "$_p" ]; then
	[ "$(readlink "$_l" 2>/dev/null || true)" = "$_p" ] || ln -sfn "$_p" "$_l"
elif [ -L "$_l" ]; then
	rm -f "$_l"
fi
unset _p _l
EOF
}

# h05_write_wrappers — H0.3 wrappers with the runtimes in the nvim PATH and,
# in "isolated" mode, the cache variables. Requires installed tools.
h05_write_wrappers() {
	H03_RUNTIME_PATH=$(h05_runtime_path)
	[ -n "$H03_RUNTIME_PATH" ] || { echo "h05_write_wrappers: no runtime installed" >&2; return 1; }
	H03_SAVED_VARS=$H05_H03_SAVED_VARS
	[ "$H05_WRAPPER" = isolated ] && H03_SAVED_VARS="$H03_SAVED_VARS $H05_CACHE_VARS"
	export H03_RUNTIME_PATH
	h03_write_wrappers || return 1
	if [ "$H05_WRAPPER" = isolated ]; then
		# tree-sitter (called by nvim-treesitter to build parsers) keeps a lock
		# in $XDG_CACHE_HOME/tree-sitter (~/.cache on Linux and macOS); its
		# H0.3 wrapper restores the host XDG_*, so give it ditto's cache.
		if _ts=$(h03_tool tree-sitter 2>/dev/null) && [ -n "$_ts" ]; then
			h03_write_tool_wrapper tree-sitter "$_ts" 'XDG_CACHE_HOME=$DITTO_ROOT/cache' || return 1
		fi
		_w="$DITTO_ROOT/bin/nvim"
		_h05_cache_exports >"$_w.cache"
		# Insert the block right before the final exec line.
		awk -v f="$_w.cache" '/^exec /{ while ((getline l < f) > 0) print l } { print }' "$_w" >"$_w.new" &&
			mv "$_w.new" "$_w" && chmod 0755 "$_w" && rm -f "$_w.cache"
	fi
}
